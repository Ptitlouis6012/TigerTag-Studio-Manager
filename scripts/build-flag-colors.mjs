#!/usr/bin/env node
// Builds renderer/quests/flag-colors.js — each country's flag colours (2 to 3,
// largest area first), read from the bundled flags (assets/svg/flags/*.svg), so
// the Tiger Squad countries league can paint a country's row in its flag.
// Re-run after the flags change:  node scripts/build-flag-colors.mjs
// (sharp is not a Studio dependency: point NODE_PATH at a checkout that has it,
// e.g. NODE_PATH=../TigerTag_Hub/node_modules.)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const sharp = require("sharp");
const DIR = join(ROOT, "assets/svg/flags");
const OUT = join(ROOT, "renderer/quests/flag-colors.js");

const hex = (r, g, b) => "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");
const out = {};
for (const f of readdirSync(DIR).filter((n) => /^[a-z]{2}\.svg$/.test(n)).sort()) {
  const { data, info } = await sharp(readFileSync(join(DIR, f)), { density: 72 })
    .resize(48, 48, { fit: "fill" }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  // Quantise to 32 levels per channel and count the area of each colour.
  const bins = new Map();
  for (let i = 0; i < data.length; i += info.channels) {
    const k = ((data[i] >> 3) << 10) | ((data[i + 1] >> 3) << 5) | (data[i + 2] >> 3);
    const b = bins.get(k) || { n: 0, r: 0, g: 0, b: 0 };
    b.n++; b.r += data[i]; b.g += data[i + 1]; b.b += data[i + 2];
    bins.set(k, b);
  }
  const total = 48 * 48;
  const cols = [...bins.values()].sort((a, b) => b.n - a.n)
    .filter((b) => b.n / total >= 0.08)                       // a real band, not an emblem's detail
    .map((b) => hex(Math.round(b.r / b.n), Math.round(b.g / b.n), Math.round(b.b / b.n)))
    .slice(0, 3);
  if (cols.length) out[f.slice(0, 2).toUpperCase()] = cols;
}
writeFileSync(OUT, `// GENERATED by scripts/build-flag-colors.mjs from assets/svg/flags — do not edit.
// Country code → its flag's main colours (2–3, largest area first).
export const FLAG_COLORS = ${JSON.stringify(out)};
`);
console.log(`[flag-colors] ${Object.keys(out).length} countries → renderer/quests/flag-colors.js`);
